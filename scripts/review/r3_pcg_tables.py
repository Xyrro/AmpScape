#!/usr/bin/env python
"""Review round 3, point 2a: truncated AMG-PCG against the learned models on the same landscapes and the same target.

T1: the cumulative current over every pair (aux/review_round3/pcg_allpairs/pcg_allpairs.json) against the stored
`cum_current` target — the quantity the learned T1 models predict. T3: the round-2 runs (aux/review_round2/cheap_baselines/
pcg.json) against the stored `current` target. Learned rows are the official runs (three seeds; per landscape the seed mean)
scored on exactly the landscapes of the PCG subset, from the `per_sample` harness results. Mean and median are both given
(round 2 compared a subset median with a whole-split mean).

  python scripts/review/r3_pcg_tables.py   -> docs/tables/review_round3_pcg.{md,json}
"""

from __future__ import annotations

import json
import pathlib
import sys

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "review"))
from r3_bootstrap import MODELS, official_runs, per_sample  # noqa: E402

KSHOW = [1, 2, 3, 4, 8, 16]


def pcg_frame(path: pathlib.Path, task: str) -> pd.DataFrame:
    rows = []
    for r in json.loads(path.read_text()):
        if r["task"] not in (task, "T1V" if task == "T1" else task) or (task == "T1" and "n_pairs" not in r):
            continue
        for k in r["k"]:
            rows.append({"tier": r["tier"], "sample_id": r["sample_id"], "k": k["k"], "rel_l2": k["rel_l2"],
                         "mae_log": k["mae_log"], "cost_s": r["t_setup_s"] + k["t_solve_s"]})
        c = r["converged_1e-6"]
        rows.append({"tier": r["tier"], "sample_id": r["sample_id"], "k": "to 1e-6", "rel_l2": c["rel_l2"],
                     "mae_log": c["mae_log"], "cost_s": r["t_setup_s"] + c["t_solve_s"]})
    return pd.DataFrame(rows)


def learned_on(task: str, tier: str, sids: set[str]) -> list[dict]:
    out = []
    for mk, mname in MODELS.items():
        runs = official_runs(mk, task, tier)
        if len(runs) < 3:
            continue
        cols = []
        for r in runs:
            d = per_sample(r, "test_id")
            if d is None:
                break
            cols.append(d[d.sample_id.isin(sids)].groupby("sample_id").rel_l2.mean())
        if len(cols) < 3:
            continue
        m = pd.concat(cols, axis=1, join="inner").mean(axis=1)
        out.append({"model": mname, "n": len(m), "rel_l2_mean": float(m.mean()), "rel_l2_median": float(m.median())})
    return out


def main() -> None:
    res, lines = {}, ["# Review round 3 — truncated AMG-PCG vs learned models on the same landscapes and target", "",
                      "PCG from zero with Circuitscape's AMG preconditioner, stopped after k iterations; cost = AMG setup + iterations, "
                      "one CPU core, mean seconds per landscape (T1: one setup per grounded node, summed over the K(K-1)/2 pairs). "
                      "T1 target: the stored cumulative current over all pairs; T3: the stored current. Learned rows: official runs, "
                      "per-landscape seed mean on the same `test_id` landscapes. Generated by `scripts/review/r3_pcg_tables.py`.", ""]
    for task, path in (("T1", ROOT / "aux/review_round3/pcg_allpairs/pcg_allpairs.json"),
                       ("T3", ROOT / "aux/review_round2/cheap_baselines/pcg.json")):
        df = pcg_frame(path, task)
        lines += [f"## {task}", "", "| tier | method | n | rel-L2 mean | rel-L2 median | cost s / landscape |", "|---|---|---|---|---|---|"]
        res[task] = {}
        for tier in ("S", "M", "L"):
            d = df[df.tier == tier]
            if d.empty:
                continue
            sids = set(d.sample_id)
            rows = []
            for k in KSHOW + ["to 1e-6"]:
                g = d[d.k.astype(str) == str(k)]
                rows.append({"method": f"PCG k={k}" if k != "to 1e-6" else "PCG to 1e-6", "n": len(g), "rel_l2_mean": float(g.rel_l2.mean()),
                             "rel_l2_median": float(g.rel_l2.median()), "cost_s": float(g.cost_s.mean())})
            cf = ROOT / f"aux/review_round2/cheap_baselines/coarsen4_{tier}.json"
            if cf.exists():
                c = pd.DataFrame(json.loads(cf.read_text()))
                c = c[(c.task == task) & c.sample_id.isin(sids)]
                if len(c):
                    rows.append({"method": "coarsen x4", "n": len(c), "rel_l2_mean": float(c.rel_l2.mean()),
                                 "rel_l2_median": float(c.rel_l2.median()), "cost_s": float(c.inference_time_s.mean())})
            r2 = json.loads((ROOT / "docs/tables/review_round2_cheap.json").read_text())
            for r in learned_on(task, tier, sids):
                inf = r2.get(f"learned_{task}_{tier}_{r['model']}", {}).get("inference_s", np.nan)
                rows.append({"method": r["model"], "n": r["n"], "rel_l2_mean": r["rel_l2_mean"], "rel_l2_median": r["rel_l2_median"],
                             "cost_s": np.nan, "gpu_s": inf})
            res[task][tier] = rows
            for r in rows:
                c = f"{r['gpu_s']:.5f} (GPU)" if np.isnan(r["cost_s"]) else f"{r['cost_s']:.3f}"
                lines.append(f"| {tier} | {r['method']} | {r['n']} | {r['rel_l2_mean']:.4f} ({r['rel_l2_mean']:.3f}) | {r['rel_l2_median']:.4f} ({r['rel_l2_median']:.3f}) | {c} |")
        lines.append("")
    out = ROOT / "docs" / "tables" / "review_round3_pcg"
    out.with_suffix(".json").write_text(json.dumps(res, indent=1))
    out.with_suffix(".md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
