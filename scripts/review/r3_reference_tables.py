#!/usr/bin/env python
"""Review round 3, point 3a: the enlarged L exact reference (original 60 + top-up 60 block-1 maps).

Reads aux/review_round3/reference/reference_L.parquet (scripts/review/r3_t4_eval.py reference) and writes
docs/tables/review_round3_reference.{md,json}: per split and method, mean rel-L2 on the original half, the new half and
all 120 (learned models: seed mean of per-seed means, fp32 inference on CPU), with a 95 % landscape-bootstrap interval on
all 120; production-target fidelity (mean, max, share above 5 %).
"""

from __future__ import annotations

import json
import pathlib

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[2]
NAMES = {"unet": "U-Net", "fno": "FNO", "vit": "ViT", "gnn": "GNN"}


def main() -> None:
    df = pd.read_parquet(ROOT / "aux" / "review_round3" / "reference" / "reference_L.parquet")
    df["half"] = np.where(df.build.str.endswith("topup"), "new", "original")
    df["method"] = df.method.map(lambda m: NAMES.get(m, m))
    rng = np.random.default_rng(20261020)
    rows = []
    for (split, method), g in df.groupby(["split", "method"]):
        if method.startswith("exact"):
            continue
        # landscapes x seeds matrix (seed 0 for the non-learned rows)
        m = g.pivot_table(index="sample_id", columns="seed", values="rel_l2")
        half = g.groupby("sample_id").half.first()
        est = {h: float(m[half.reindex(m.index) == h].mean(axis=0).mean()) for h in ("original", "new")}
        a = m.to_numpy()
        bs = a[rng.integers(0, len(a), size=(2000, len(a)))].mean(axis=1).mean(axis=1)
        r = {"split": split, "method": method, "n": len(m), "original": est["original"], "new": est["new"],
             "all": float(a.mean(axis=0).mean()), "ci_lo": float(np.percentile(bs, 2.5)), "ci_hi": float(np.percentile(bs, 97.5))}
        if method.startswith("production"):
            v = g.rel_l2.to_numpy()
            r.update({"max": float(v.max()), "n_above_5pct": int((v > 0.05).sum())})
        rows.append(r)
    lines = ["# Review round 3 — T4 at L against the enlarged exact block-1 reference (60 original + 60 new landscapes)", "",
             "rel-L2 against the exact block-1 map; learned rows are the official runs (three seeds, fp32 inference on CPU; the "
             "Pareto table used bf16 on GPU), seed mean of per-seed means; 95 % interval over 2,000 landscape resamples on all landscapes. "
             "Generated by `scripts/review/r3_reference_tables.py`.", "",
             "| split | method | n (all) | original half | new half | all | 95 % CI (all) |", "|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["split"], r["all"])):
        lines.append(f"| {r['split']} | {r['method']} | {r['n']} | {r['original']:.4f} | {r['new']:.4f} | {r['all']:.4f} | [{r['ci_lo']:.4f}, {r['ci_hi']:.4f}] |")
    prod = df[df.method.str.startswith("production")]
    v = prod.rel_l2.to_numpy()
    lines += ["", f"Production target (block 5) against block 1 on all {len(v)} landscapes: mean {v.mean():.4f}, median {np.median(v):.4f}, "
              f"max {v.max():.4f}, {int((v > 0.05).sum())} of {len(v)} above 5 % "
              f"({int(((v > 0.05) & (prod.family != 'real').to_numpy()).sum())} synthetic). Exact solves: median "
              f"{df[df.method.str.startswith('exact')].time_s.median():.0f} s per landscape on one core."]
    out = ROOT / "docs" / "tables" / "review_round3_reference"
    out.with_suffix(".json").write_text(json.dumps(rows, indent=1))
    out.with_suffix(".md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
