#!/usr/bin/env python
"""Review round 3, point 1: tables for the independent source-rule experiment (scripts/review/r3_t4_eval.py models).

For each tier and source rule: the official T4 models' rel-L2 (and top-5 % IoU, Spearman) against the Omniscape map of
that rule, with the rule's true source raster as input ("true") and with the production source raster swapped in
("swapped"); plus the production-rule solver map used as the prediction ("unchanged map": how much the answer moved).
Seed mean of per-seed landscape means; three seeds per model.

  python scripts/review/r3_source_ood_tables.py   -> docs/tables/review_round3_source_ood.{md,json}
"""

from __future__ import annotations

import json
import pathlib

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "aux" / "review_round3" / "source_ood"
NAMES = {"unet": "U-Net", "fno": "FNO", "vit": "ViT", "gnn": "GNN", "mgno": "MgNO", "unchanged": "unchanged map"}
RULES = ["default", "uniform", "random_field", "habitat_core"]
RULE_TEXT = {"default": "production rule (in-distribution)", "uniform": "uniform", "random_field": "random field (independent of R)",
             "habitat_core": "habitat core ((1/R)^2, top 20 %)"}


def main() -> None:
    res, lines = {}, ["# Review round 3 — T4 under source rules the models never saw", "",
                      "Same test_id landscapes and Omniscape geometry, only the source raster changes (`scripts/review/r3_build_from_hub.py`). "
                      "`true`: the rule's source raster as input; `swapped`: the production source raster as input (a model that ignored its "
                      "source channel would score the same); `unchanged map`: the production-rule solver map as the prediction. "
                      "rel-L2 / top-5 % IoU / Spearman against the exact Omniscape map of the rule; seed mean of per-seed means. "
                      "Generated by `scripts/review/r3_source_ood_tables.py`.", ""]
    for tier in ("S", "M"):
        f = SRC / f"models_{tier}.parquet"
        if not f.exists():
            continue
        df = pd.read_parquet(f)
        n = df[df.model != "unchanged"].groupby("rule").sample_id.nunique().to_dict()
        agg = (df.groupby(["model", "seed", "rule", "input"])[["rel_l2", "top5_iou", "spearman"]].mean()
               .groupby(["model", "rule", "input"]).mean().reset_index())
        res[tier] = {"n": n, "rows": agg.to_dict(orient="records")}
        lines += [f"## {tier} (landscapes per rule: {', '.join(f'{r} {n.get(r, 0)}' for r in RULES)})", "",
                  "| model | input | " + " | ".join(RULE_TEXT[r] for r in RULES) + " |", "|---|---|" + "---|" * len(RULES)]
        for model in ["unet", "fno", "vit", "gnn", "mgno", "unchanged"]:
            for inp in (["-"] if model == "unchanged" else ["true", "swapped"]):
                key = "production" if inp == "swapped" else inp
                cells = []
                for r in RULES:
                    if inp == "swapped" and r == "default":
                        cells.append("= true")
                        continue
                    g = agg[(agg.model == model) & (agg.rule == r) & (agg.input == key)]
                    cells.append("—" if g.empty else f"{g.rel_l2.iloc[0]:.3f} / {g.top5_iou.iloc[0]:.2f} / {g.spearman.iloc[0]:.2f}")
                if model == "unchanged":
                    cells[0] = "0 (identical)"
                lines.append(f"| {NAMES[model]} | {inp} | " + " | ".join(cells) + " |")
        lines.append("")
        # ratio summary: true-source error relative to the in-distribution error, and swapped vs true
        lines += [f"### {tier}: summary (official models, MgNO excluded)", "", "| rule | rel-L2 true / in-distribution (min–max over models) | swapped / true (min–max) | unchanged map rel-L2 |", "|---|---|---|---|"]
        a = agg[agg.model.isin(["unet", "fno", "vit", "gnn"])]
        for r in RULES[1:]:
            t = a[(a.rule == r) & (a.input == "true")].set_index("model").rel_l2
            i = a[(a.rule == "default") & (a.input == "true")].set_index("model").rel_l2
            s = a[(a.rule == r) & (a.input == "production")].set_index("model").rel_l2
            u = agg[(agg.model == "unchanged") & (agg.rule == r)].rel_l2
            q1, q2 = (t / i).dropna(), (s / t).dropna()
            lines.append(f"| {RULE_TEXT[r]} | {q1.min():.2f}–{q1.max():.2f} | {q2.min():.2f}–{q2.max():.2f} | {u.iloc[0] if len(u) else float('nan'):.3f} |")
        lines.append("")
    # overall figures quoted in the paper (official models, MgNO excluded, both tiers)
    mx, sp, lo, hi = 0.0, 1.0, {}, {}
    for tier, v in res.items():
        ag = {(r["model"], r["rule"], r["input"]): r for r in v["rows"]}
        for m in ("unet", "fno", "vit", "gnn"):
            for rule in RULES[1:]:
                mx = max(mx, abs(ag[(m, rule, "production")]["rel_l2"] / ag[("unchanged", rule, "-")]["rel_l2"] - 1))
                sp = min(sp, ag[(m, rule, "true")]["spearman"])
                t = ag[(m, rule, "true")]["rel_l2"]
                lo[tier], hi[tier] = min(lo.get(tier, 9), t), max(hi.get(tier, 0), t)
    lines += ["## Overall (official models, MgNO excluded)", "",
              "- true-source rel-L2 range: " + "; ".join(f"{t} {lo[t]:.3f}–{hi[t]:.3f}" for t in lo),
              f"- largest relative difference between a swapped-input error and the unchanged map's error: {mx * 100:.1f} %",
              f"- lowest Spearman with the true sources: {sp:.2f}", ""]
    out = ROOT / "docs" / "tables" / "review_round3_source_ood"
    out.with_suffix(".json").write_text(json.dumps(res, indent=1, default=float))
    out.with_suffix(".md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
